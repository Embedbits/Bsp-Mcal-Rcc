/**
 * \author Mr.Nobody
 * \file Rcc_ClkMux.c
 * \ingroup Rcc
 * \brief Rcc module ClkMux component functionality.
 *
 * The ClkMux component controls the peripheral kernel clock multiplexers
 * (clock source selection fields in the RCC D1CCIPR / D2CCIP1R / D2CCIP2R /
 * D3CCIPR - CDCCIPR / CDCCIP1R / CDCCIP2R / SRDCCIPR, CCIPR1 - CCIPR4 on
 * STM32H7R / H7S - and BDCR registers).
 * All MCU specific knowledge is stored in the constant array
 * rcc_ClkMuxConfig[]; the functions only look up a record and read or write
 * the register field described by that record.
 *
 * \par Structure of rcc_ClkMuxConfig[]
 * One record (rcc_ClkMuxConfigStruct_t) describes one selectable clock source
 * of one clock multiplexer:
 * - ClkMuxId        - ID of this record (rcc_ClkMuxId_t, Rcc_ClkMux.h).
 * - BlockId         - Peripheral block clocked through this multiplexer
 *                     (rcc_BlockList_t, Rcc.h) - the first peripheral of a
 *                     multiplexer shared by several peripherals.
 * - ClkMuxRegId     - RCC register containing the multiplexer field.
 * - ClkSrcMask      - Bit mask of the multiplexer field in that register.
 * - ClkSrcVal       - Value selecting this clock source - either the raw field
 *                     value (within ClkSrcMask, RTC) or the LL_CLKSOURCE()
 *                     encoded value (register offset, position, mask and field
 *                     value). Both forms are converted to the field value by
 *                     Rcc_ClkMux_Get_FieldVal().
 * - DefaultClkMuxId - Record holding the default (reset) selection of this
 *                     multiplexer.
 *
 * Records of the kernel clock selection registers are written by
 * \ref RCC_CLK_MUX_RECORD from the LL_CLKSOURCE() encoded clock source - register
 * and mask of the record are derived from the encoded value. Multiplexers which
 * LL does not encode (raw field values) are encoded by LL_CLKSOURCE() with the
 * register / field of the selected device line.
 *
 * Records belonging to one multiplexer form a group. They share the same
 * BlockId, ClkMuxRegId, ClkSrcMask and DefaultClkMuxId and differ only in
 * ClkMuxId and ClkSrcVal. The default record is the first record of the
 * group.
 *
 * \par Rules for adding or changing records
 * - The records must be in exactly the same order as rcc_ClkMuxId_t, because
 *   the array is indexed directly by ClkMuxId. Rcc_ClkMux_Init() verifies
 *   that rcc_ClkMuxConfig[ i ].ClkMuxId == i and a _Static_assert verifies
 *   the size of the array.
 * - The kernel clock tables are generated from the CMSIS / LL headers of all
 *   STM32H7 devices (guards select the records of the device).
 *
 */
