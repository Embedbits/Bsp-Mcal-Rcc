/* ========================== SYMBOLIC CONSTANTS ============================ */

/** Maximal wait time for configuration request confirmation */
#define RCC_CLKMUX_TIMEOUT_RAW             ( 0x84FCB )

/** Byte offset between consecutive kernel clock selection registers */
#define RCC_CLKMUX_REG_OFFSET_SHIFT        ( 2u )

/* ============================== TYPEDEFS ================================== */

/**
 * \brief Clock tree configuration structure
 */
typedef struct __attribute__((packed))
{
    rcc_ClkMuxId_t          ClkMuxId;         /**< Peripheral ID                    */
    rcc_BlockList_t         BlockId;          /**< Peripheral block ID              */
    rcc_RegId_t             ClkMuxRegId;      /**< Clock MUX register ID.           */
    volatile uint32_t const ClkSrcMask;       /**< Clock MUX bit mask.              */
    volatile uint32_t const ClkSrcVal;        /**< Clock MUX value.                 */
    rcc_ClkMuxId_t          DefaultClkMuxId;  /**< Peripheral default configuration */
}   rcc_ClkMuxConfigStruct_t;

/* ======================== FORWARD DECLARATIONS ============================ */

static uint32_t           Rcc_ClkMux_Get_FieldVal ( rcc_ClkMuxId_t clkMuxId );
static rcc_RequestState_t Rcc_ClkMux_Check_Record ( rcc_ClkMuxId_t clkMuxId );

/* =============================== MACROS =================================== */

/**
 * \brief Record of a kernel clock selection register multiplexer input.
 *
 * \param muxId     [in]: Record ID (\ref rcc_ClkMuxId_t)
 * \param blockId   [in]: Peripheral block of the multiplexer (\ref rcc_BlockList_t)
 * \param llClkSrc  [in]: LL_CLKSOURCE() encoded clock source
 * \param dfltMuxId [in]: Record ID of the default selection of the multiplexer
 */
#define RCC_CLK_MUX_RECORD( muxId, blockId, llClkSrc, dfltMuxId )                                                   \
    { .ClkMuxId        = ( muxId ),                                                                                 \
      .BlockId         = ( blockId ),                                                                               \
      .ClkMuxRegId     = (rcc_RegId_t)( (uint32_t)RCC_REG_D1CCIPR + ( LL_CLKSOURCE_REG( llClkSrc ) >> RCC_CLKMUX_REG_OFFSET_SHIFT ) ), \
      .ClkSrcMask      = LL_CLKSOURCE_MASK( llClkSrc ),                                                             \
      .ClkSrcVal       = ( llClkSrc ),                                                                              \
      .DefaultClkMuxId = ( dfltMuxId ) }

